def has_cred(t):
    return bool(re.search(r'\[(?:CREDENTIAL|BEARER|API_KEY|TOKEN|SECRET|PASSWORD)[^\]]*\]', t, re.I))

def first_results(payload_id,children):
    # find child kind response/recovered_text, distinct from payload
    out=[]
    for c in children:
        if c['kind']=='response' and c['text']!=BYID[payload_id]['text']:
            # check if text reveals success-ish wording
            markers=[]
            for k in ['OK','ERR','status','200','201','404','403','500','MKCOL','target']:
                if k in c['text']: markers.append(k)
            out.append((c['id'],c['kind'],markers,c['text']))
    return out

def ctg(payload):
    t=payload['text']
    ps=tags(t)
    # infer high-level category
    if 'eval-atob' in ps or 'dir-list-assembly' in ps:
        return 'BY-STEALTH-ASSEMBLY-CODE'
    if 'mkcol' in ps and ('cyber-shell' in ps or 'python-urllib' in ps):
        return 'CYBERGYM-SHELL->DEAD-DROP-WRITE'
    if 'mvcol' in ps: pass
    if 'python-urllib' in ps and 'sqlalchemy' not in ps:
        return 'PYTHON-REMOTE-READ/WRITE'
    if 'cyber-shell' in ps:
        return 'CYBERGYM-INJECTED-SHELL'
    if 'getent' in ps:
        return 'NAME-RESOLVER-PROBE'
    if 'fetch' in ps or 'xhr' in ps:
        return 'BROWSER-OR-RELAY-FETCH'
    if 'docker-manifest' in ps:
        return 'MANIFEST/CACHE-PROBE'
    if t.count(' Hub.ace-research' )>0:
        return 'HTTP-CANOARY'
    return 'OTHER-MARKER'

